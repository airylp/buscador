/// Un píxel del ícono ya sombreado.
#[derive(Clone, Copy)]
struct Px {
    x: u8,
    y: u8,
    rgb: [u8; 3],
    alpha: u8,
}

fn parse_art() -> HashMap<String, Vec<Vec<u8>>> {
    let mut out: HashMap<String, Vec<Vec<u8>>> = HashMap::new();
    let mut cur: Option<String> = None;
    for line in ART.lines().map(str::trim).filter(|l| !l.is_empty()) {
        if let Some(name) = line.strip_prefix('@') {
            if let Some((n, src)) = name.split_once('=') {
                let (from, how) = src.split_once('|').unwrap_or((src, ""));
                let mut rows = out.get(from).cloned().unwrap_or_default();
                if how == "h" {
                    for r in &mut rows {
                        r.reverse();
                    }
                }
                out.insert(n.to_string(), rows);
                cur = None;
            } else {
                out.insert(name.to_string(), Vec::new());
                cur = Some(name.to_string());
            }
        } else if let Some(n) = &cur {
            out.get_mut(n).unwrap().push(line.as_bytes().to_vec());
        }
    }
    out
}

fn base(c: u8) -> Option<[u8; 3]> {
    PALETTE.iter().find(|(k, _)| *k == c).map(|(_, v)| *v)
}

fn mix(c: [u8; 3], f: f32) -> [u8; 3] {
    let m = |v: u8| -> u8 {
        let v = v as f32;
        (if f >= 1.0 { v + (255.0 - v) * (f - 1.0) } else { v * f }).round().clamp(0.0, 255.0) as u8
    };
    [m(c[0]), m(c[1]), m(c[2])]
}

/// Píxeles sombreados de `rows`: relieve de cada zona de color, contorno y sombra.
fn shade(rows: &[Vec<u8>]) -> Vec<Px> {
    let at = |x: i32, y: i32| -> u8 {
        if x < 0 || y < 0 || y >= rows.len() as i32 || x >= rows[y as usize].len() as i32 { b'.' } else { rows[y as usize][x as usize] }
    };
    let filled = |x: i32, y: i32| base(at(x, y)).is_some();
    let mut out = Vec::new();
    for y in 0..16i32 {
        for x in 0..16i32 {
            let c = at(x, y);
            if let Some(b) = base(c) {
                let lit = at(x, y - 1) != c || at(x - 1, y) != c;
                let dark = at(x, y + 1) != c || at(x + 1, y) != c;
                let rgb = match (lit, dark) {
                    (true, false) => mix(b, 1.40),
                    (false, true) => mix(b, 0.78),
                    _ => b,
                };
                out.push(Px { x: x as u8, y: y as u8, rgb, alpha: 255 });
            } else {
                // Contorno: casilla vacía junto a una llena (4 vecinas) → color oscuro
                // de la vecina; si no, sombra proyectada si la de arriba a la izquierda
                // está llena o es contorno.
                let near = [(0, -1), (-1, 0), (1, 0), (0, 1)].iter().find_map(|&(dx, dy)| base(at(x + dx, y + dy)));
                if let Some(b) = near {
                    out.push(Px { x: x as u8, y: y as u8, rgb: mix(b, 0.42), alpha: 255 });
                } else if filled(x - 1, y - 1) || filled(x - 2, y - 1) || filled(x - 1, y - 2) {
                    out.push(Px { x: x as u8, y: y as u8, rgb: [0, 0, 0], alpha: 46 });
                }
            }
        }
    }
    out
}

fn pixels(icon: Icon) -> Arc<Vec<Px>> {
    static CACHE: OnceLock<Mutex<HashMap<Icon, Arc<Vec<Px>>>>> = OnceLock::new();
    let cache = CACHE.get_or_init(|| Mutex::new(HashMap::new()));
    let mut c = cache.lock().unwrap();
    c.entry(icon)
        .or_insert_with(|| {
            static ARTS: OnceLock<HashMap<String, Vec<Vec<u8>>>> = OnceLock::new();
            let arts = ARTS.get_or_init(parse_art);
            Arc::new(arts.get(&format!("{icon:?}")).map(|r| shade(r)).unwrap_or_default())
        })
        .clone()
}

/// Cómo pintar: a todo color, apagado (deshabilitado) o de un solo color.
#[derive(Clone, Copy, PartialEq)]
pub enum Look {
    Color,
    Disabled,
    Tint(Color32),
}

/// Pinta `icon` en `rect` (cuadrado). Cada píxel del dibujo se alinea a los de la pantalla.
pub fn paint_look(p: &Painter, rect: Rect, icon: Icon, look: Look) {
    let ppp = p.pixels_per_point();
    let side = rect.width().min(rect.height());
    // Tamaño del «píxel» del dibujo en píxeles reales: entero si se puede (nítido).
    let real = ((side * ppp) / 16.0).floor().max(1.0);
    let k = real / ppp;
    let o = rect.center() - Vec2::splat(8.0 * k);
    let o = pos2((o.x * ppp).round() / ppp, (o.y * ppp).round() / ppp);
    let mut mesh = Mesh::default();
    for px in pixels(icon).iter() {
        let col = match look {
            Look::Color => Color32::from_rgba_unmultiplied(px.rgb[0], px.rgb[1], px.rgb[2], px.alpha),
            Look::Disabled => {
                let g = (px.rgb[0] as u32 * 3 + px.rgb[1] as u32 * 6 + px.rgb[2] as u32) / 10;
                Color32::from_rgba_unmultiplied(g as u8, g as u8, g as u8, (px.alpha as u32 * 90 / 255) as u8)
            }
            Look::Tint(t) => {
                if px.alpha < 255 {
                    continue;
                }
                t
            }
        };
        let r = Rect::from_min_size(o + vec2(px.x as f32, px.y as f32) * k, Vec2::splat(k));
        mesh.add_colored_rect(r, col);
    }
    p.add(Shape::mesh(mesh));
}

/// Pinta `icon` a todo color.
pub fn paint(p: &Painter, rect: Rect, icon: Icon) {
    paint_look(p, rect, icon, Look::Color);
}

/// Familia de colores de cada grupo de botones (fondo del botón activo).
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Tone {
    File,
    Edit,
    Search,
    Tool,
    Live,
    Neutral,
}

impl Tone {
    pub fn color(self, ui: &Ui) -> Color32 {
        let dark = ui.visuals().dark_mode;
        let (d, l) = match self {
            Tone::File => ((126, 172, 226), (44, 104, 168)),
            Tone::Edit => ((222, 182, 112), (160, 106, 26)),
            Tone::Search => ((108, 196, 180), (26, 126, 110)),
            Tone::Tool => ((172, 158, 228), (104, 84, 176)),
            Tone::Live => ((112, 202, 122), (38, 140, 60)),
            Tone::Neutral => ((150, 160, 175), (90, 100, 115)),
        };
        let (r, g, b) = if dark { d } else { l };
        Color32::from_rgb(r, g, b)
    }
}

/// Botón de barra: ícono (opcional) + texto (opcional), fondo solo al pasar el
/// ratón y un tinte suave del color del grupo cuando está activo.
pub struct IconButton {
    icon: Option<Icon>,
    text: Option<String>,
    selected: bool,
    tone: Tone,
    small: bool,
    framed: bool,
    primary: bool,
}

impl IconButton {
    pub fn new(icon: Icon, tone: Tone) -> Self {
        IconButton { icon: Some(icon), text: None, selected: false, tone, small: false, framed: false, primary: false }
    }

    /// Solo texto (p. ej. «Aa», «.*»), con el mismo aspecto que los demás.
    pub fn text_only(text: impl Into<String>, tone: Tone) -> Self {
        IconButton { icon: None, text: Some(text.into()), selected: false, tone, small: false, framed: false, primary: false }
    }

    pub fn label(mut self, text: impl Into<String>) -> Self {
        let t = text.into();
        self.text = (!t.is_empty()).then_some(t);
        self
    }

    pub fn selected(mut self, on: bool) -> Self {
        self.selected = on;
        self
    }

    /// Con fondo y borde siempre visibles (botones grandes, p. ej. la bienvenida).
    pub fn framed(mut self) -> Self {
        self.framed = true;
        self
    }

    /// Acción principal: relleno con el color de la app, ícono y letra en blanco.
    pub fn primary(mut self) -> Self {
        self.primary = true;
        self
    }

    /// Versión para la barra de estado: más baja y con letra pequeña.
    pub fn small(mut self) -> Self {
        self.small = true;
        self
    }
}

impl Widget for IconButton {
    fn ui(self, ui: &mut Ui) -> Response {
        let enabled = ui.is_enabled();
        let tint = self.tone.color(ui);
        let (h, s, style) = if self.small {
            (ui.spacing().interact_size.y - 2.0, 16.0, TextStyle::Small)
        } else {
            (ui.spacing().interact_size.y + if self.framed { 12.0 } else { 4.0 }, 16.0, TextStyle::Button)
        };
        // El margen sale de `button_padding` (la barra lo reduce si la ventana es estrecha).
        let pad = ui.spacing().button_padding.x - if self.small { 2.0 } else { 0.0 } + if self.framed { 8.0 } else { 0.0 };
        let gap = if self.small { 3.0 } else { 5.0 };
        let galley = self.text.as_ref().map(|t| WidgetText::from(t.as_str()).into_galley(ui, Some(eframe::egui::TextWrapMode::Extend), f32::INFINITY, style));
        let mut w = pad * 2.0;
        if self.icon.is_some() {
            w += s;
        }
        if let Some(g) = &galley {
            w += g.size().x + if self.icon.is_some() { gap } else { 0.0 };
        }
        let w = w.max(h);
        let (rect, resp) = ui.allocate_exact_size(vec2(w, h), Sense::click());
        let label = self.text.clone().unwrap_or_else(|| format!("{:?}", self.icon.unwrap_or(Icon::Chevron)));
        resp.widget_info(|| WidgetInfo::selected(eframe::egui::Role::Button, enabled, self.selected, &label));
        if ui.is_rect_visible(rect) {
            let v = ui.visuals();
            let radius = CornerRadius::same(if self.small { 4 } else { 6 });
            let primary = self.primary && enabled;
            if primary {
                let c = crate::estilo::acento();
                let f = if resp.is_pointer_button_down_on() { c.lerp_to_gamma(Color32::BLACK, 0.25) } else if resp.hovered() { c.lerp_to_gamma(Color32::BLACK, 0.12) } else { c };
                ui.painter().rect(rect, radius, f, Stroke::new(1.0, c.lerp_to_gamma(Color32::BLACK, 0.2)), StrokeKind::Inside);
            } else if self.selected {
                ui.painter().rect(rect, radius, tint.gamma_multiply(if v.dark_mode { 0.22 } else { 0.16 }), Stroke::new(1.0, tint.gamma_multiply(0.7)), StrokeKind::Inside);
            } else if enabled && (resp.hovered() || resp.has_focus()) {
                let f = if resp.is_pointer_button_down_on() { v.widgets.active.weak_bg_fill } else { v.widgets.hovered.weak_bg_fill };
                ui.painter().rect(rect, radius, f, if self.framed { v.widgets.hovered.bg_stroke } else { Stroke::NONE }, StrokeKind::Inside);
            } else if self.framed {
                ui.painter().rect(rect, radius, v.widgets.inactive.weak_bg_fill, v.widgets.inactive.bg_stroke, StrokeKind::Inside);
            }
            let mut x = rect.left() + pad;
            if self.icon.is_none() {
                x = rect.center().x - galley.as_ref().map_or(0.0, |g| g.size().x) / 2.0;
            }
            if let Some(icon) = self.icon {
                // Al pulsar, el ícono «se hunde» un píxel.
                let down = if enabled && resp.is_pointer_button_down_on() { 1.0 } else { 0.0 };
                let r = Rect::from_center_size(pos2(x + s / 2.0, rect.center().y + down), Vec2::splat(s));
                paint_look(ui.painter(), r, icon, if primary { Look::Tint(Color32::WHITE) } else if enabled { Look::Color } else { Look::Disabled });
                x += s + gap;
            }
            if let Some(g) = galley {
                let tc = if primary {
                    Color32::WHITE
                } else if !enabled {
                    v.weak_text_color().gamma_multiply(0.7)
                } else if self.selected {
                    v.strong_text_color()
                } else if self.icon.is_none() {
                    tint
                } else {
                    v.text_color()
                };
                ui.painter().galley(pos2(x, rect.center().y - g.size().y / 2.0), g, tc);
            }
        }
        resp
    }
}

/// Punto de aviso (p. ej. versión nueva) en la esquina de un botón.
pub fn badge(ui: &Ui, r: &Response, color: Color32) {
    let c = r.rect.right_top() + vec2(-4.0, 4.0);
    ui.painter().circle_filled(c, 3.5, color);
    ui.painter().circle_stroke(c, 3.5, Stroke::new(1.0, ui.visuals().panel_fill));
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Todos los íconos existen, miden 16×16 y solo usan colores de la paleta.
    #[test]
    fn art_is_complete() {
        let arts = parse_art();
        for icon in Icon::ALL {
            let name = format!("{icon:?}");
            let rows = arts.get(&name).unwrap_or_else(|| panic!("falta el dibujo de {name}"));
            assert_eq!(rows.len(), 16, "{name}: {} filas", rows.len());
            for (i, r) in rows.iter().enumerate() {
                assert_eq!(r.len(), 16, "{name}, fila {i}: {} columnas", r.len());
                assert!(r.iter().all(|&c| c == b'.' || base(c).is_some()), "{name}, fila {i}: color desconocido");
            }
        }
        // ICONOS_PNG=archivo.png guarda una hoja con todos (a 2×) para verlos.
        if let Ok(path) = std::env::var("ICONOS_PNG") {
            let (cols, cell) = (12usize, 40usize);
            let n = Icon::ALL.len().div_ceil(cols);
            let size = cols * cell;
            let mut rgba = vec![0u8; size * size * 4];
            for y in 0..size {
                for x in 0..size {
                    // Mitad izquierda clara, derecha oscura.
                    let g = if y < n * cell / 2 + 1000 && x < size / 2 { 236 } else { 40 };
                    rgba[(y * size + x) * 4..][..4].copy_from_slice(&[g, g, g, 255]);
                }
            }
            for (i, icon) in Icon::ALL.iter().enumerate() {
                let (ox, oy) = ((i % cols) * cell + 4, (i / cols) * cell + 4);
                for p in shade(&arts[&format!("{icon:?}")]) {
                    for dy in 0..2 {
                        for dx in 0..2 {
                            let (x, y) = (ox + p.x as usize * 2 + dx, oy + p.y as usize * 2 + dy);
                            let j = (y * size + x) * 4;
                            let a = p.alpha as u32;
                            for k in 0..3 {
                                rgba[j + k] = ((p.rgb[k] as u32 * a + rgba[j + k] as u32 * (255 - a)) / 255) as u8;
                            }
                        }
                    }
                }
            }
            std::fs::write(path, crate::icon::png_of(&rgba, size)).unwrap();
        }
    }
}
